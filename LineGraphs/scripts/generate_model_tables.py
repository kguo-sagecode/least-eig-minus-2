#!/usr/bin/env python3
"""Untrusted materialization of the other E8 models. Lean checks every table bridge."""
from itertools import combinations, product
from pathlib import Path
from lean_output import write_lean

OUT = Path(__file__).resolve().parents[1] / 'Computations'

def key(v):
    k = 0
    for x in v:
        k = 7 * k + x + 3
    return k

def tree(vs, indent=2):
    if not vs:
        return '.nil'
    m = len(vs) // 2
    v = vs[m]
    pad = '\n' + ' ' * indent
    return f'(.node {key(v)} {v}{pad}{tree(vs[:m], indent+2)}{pad}{tree(vs[m+1:], indent+2)})'

aroots = []
for i in range(9):
    for j in range(9):
        if i != j:
            v = [0] * 9
            v[i], v[j] = 3, -3
            aroots.append(v)
for t in combinations(range(9), 3):
    for sign in (1, -1):
        aroots.append([sign * (-2 if i in t else 1) for i in range(9)])
blocks = [(0,1,2,3), (0,1,4,5), (0,1,6,7), (0,2,4,6), (0,2,5,7),
          (0,3,4,7), (0,3,5,6), (1,2,4,7), (1,2,5,6), (1,3,4,6),
          (1,3,5,7), (2,3,4,5), (2,3,6,7), (4,5,6,7)]
sroots = []
for i in range(8):
    for sign in (2, -2):
        v = [0] * 8
        v[i] = sign
        sroots.append(v)
for b in blocks:
    for signs in product((-1, 1), repeat=4):
        v = [0] * 8
        for i, x in zip(b, signs):
            v[i] = x
        sroots.append(v)
source = '''/-
Copyright (c) 2026 Krystal Guo. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Krystal Guo
-/
import LineGraphs.Computations.VectorTree

/-! Materialized integer data for the nine-coordinate and Steiner models.
Generated by `generate_model_tables.py`; all connections with the models are proved in Lean.
This module intentionally has no dependency on real vectors or the structured indices. -/

namespace Computations

/-- Base seven accommodates the coordinates from minus three to three. -/
def modelVectorKey (v : IntVector) : ℤ := v.foldl (fun k x ↦ 7 * k + x + 3) 0

'''
for name, roots in [('e₈A', aroots), ('e₈Steiner', sroots)]:
    roots.sort()
    assert len(set(map(tuple, roots))) == 240
    source += f'def {name}Tree : VectorTree :=\n  {tree(roots)}\n\n'
    source += f'def {name}Roots : List IntVector := {name}Tree.vectors\n\n'
    source += f'def {name}Decode (v : IntVector) : Bool := {name}Tree.lookup (modelVectorKey v) v\n\n'
source += 'end Computations\n'
write_lean(OUT / 'ExceptionalData.lean', source, 'Exceptional integer root data')

def finset(xs):
    return '{' + ', '.join(map(str, xs)) + '}' if xs else '∅'

def aindex(v):
    if 3 in v:
        i, j = v.index(3), v.index(-3)
        return f'.inl ⟨({i}, {j}), by decide⟩'
    positive = -2 in v
    t = [i for i, x in enumerate(v) if x == (-2 if positive else 2)]
    return f'.inr (⟨{finset(t)}, by decide⟩, {str(not positive).lower()})'

def sindex(v):
    if 2 in v or -2 in v:
        i = next(i for i, x in enumerate(v) if x)
        return f'.inl ({i}, {str(v[i] < 0).lower()})'
    b = [i for i, x in enumerate(v) if x]
    neg = [i for i, x in enumerate(v) if x < 0]
    return f'.inr ⟨⟨{finset(b)}, by decide⟩, fun i ↦ decide (i.val ∈ ({finset(neg)} : Finset (Fin 8)))⟩'

for name, file, roots, idx, root, index in [
    ('e₈A', 'E8ATable', aroots, 'E₈AIndex', 'e₈ARoot', aindex),
    ('e₈Steiner', 'E8SteinerTable', sroots, 'E₈SteinerIndex', 'e₈SteinerRoot', sindex)]:
    code = '''/-
Copyright (c) 2026 Krystal Guo. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Krystal Guo
-/
import LineGraphs.Computations.RootTables
import LineGraphs.LineSystem.Models
import LineGraphs.Computations.ExceptionalData

/-! Single-pass, twenty-root certificates for a materialized exceptional table.
Generated by `generate_model_tables.py`; all data are checked by the Lean kernel. -/

namespace Computations

'''
    for k in range(12):
        chunk = roots[20*k:20*k+20]
        vals = ',\n   '.join(index(v) for v in chunk)
        code += f'def {name}Indices{k} : List LineSystem.{idx} :=\n  [{vals}]\n\n'
        code += f'''theorem {name}_table_chunk_{k} : ({name}Roots.drop {20*k}).take 20 =
    {name}Indices{k}.map (fun a ↦ List.ofFn (LineSystem.{root} a)) := by
  decide +kernel

'''
    code += f'def {name}Indices : List LineSystem.{idx} :=\n  '
    code += ' ++\n  '.join(f'{name}Indices{k}' for k in range(12)) + '\n\n'
    code += f'''theorem {name}Roots_eq_map : {name}Roots =
    {name}Indices.map (fun a ↦ List.ofFn (LineSystem.{root} a)) := by
  simp only [{name}Indices, List.map_append,
    ''' + ',\n    '.join(f'← {name}_table_chunk_{k}' for k in range(12)) + ''']
  decide +kernel

'''
    code += f'''theorem {name}Roots_nodup : {name}Roots.Nodup := by
  have h : ({name}Roots.map modelVectorKey).IsChain (· < ·) := by decide +kernel
  exact List.Nodup.of_map modelVectorKey (List.isChain_iff_pairwise.mp h).nodup

theorem {name}Roots_length : {name}Roots.length = 240 := by decide +kernel

theorem mem_{name}Indices (a : LineSystem.{idx}) : a ∈ {name}Indices :=
  mem_indices_of_image {name}Roots_eq_map {name}Roots_nodup
    ({name}Roots_length.trans LineSystem.card_{idx}.symm) a

theorem mem_{name}Roots (w : IntVector) :
    w ∈ {name}Roots ↔ ∃ a, List.ofFn (LineSystem.{root} a) = w := by
  rw [{name}Roots_eq_map]
  exact mem_indexedRootTable {name}Indices mem_{name}Indices LineSystem.{root} w

theorem {name}_decode_complete : {name}Roots.all {name}Decode = true := by decide +kernel

theorem {name}Decode_iff (v : IntVector) : {name}Decode v = true ↔ v ∈ {name}Roots :=
  ⟨VectorTree.lookup_sound, fun h ↦ List.all_eq_true.mp {name}_decode_complete v h⟩

end Computations
'''
    write_lean(OUT / f'{file}.lean', code, 'Certified exceptional root table')
