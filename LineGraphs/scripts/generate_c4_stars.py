#!/usr/bin/env python3
"""Reflection trees for C4 on every ordered star of E8, E7 and E6.

The root tables are model (ii) of E8 in doubled coordinates, sorted lexicographically (the order
of `E₈viaD₈.rootList`), and its filters for E7 (x7 = x8) and E6 (x6 = x7 = x8). For each model
and its fixed star (a0, b0) of `C4E*.lean`, it writes two breadth-first trees:

* over all roots from a0, with the reflection in p - i carrying the parent p to i;
* over the roots i with (i, a0) = -1, from b0, with the same rule; the reflecting root p - i is
  then orthogonal to a0.

Every entry is rechecked by `decide +kernel` in `C4E*Stars.lean`; this script only finds them.
Usage: generate_c4_stars.py > ../Computations/C4StarData.lean
"""
import itertools

def e8_roots():
    roots = set()
    for i, j in itertools.combinations(range(8), 2):
        for s, t in itertools.product((2, -2), repeat=2):
            v = [0] * 8; v[i] = s; v[j] = t; roots.add(tuple(v))
    for signs in itertools.product((1, -1), repeat=8):
        if signs.count(-1) % 2 == 0:
            roots.add(signs)
    return sorted(roots)

E8 = e8_roots()
E7 = [v for v in E8 if v[6] == v[7]]
E6 = [v for v in E7 if v[5] == v[6]]
Q = 4
dot = lambda u, v: sum(a * b for a, b in zip(u, v))
MODELS = [("e8", E8, 239, 12), ("e7", E7, 125, 8), ("e6", E6, 71, 6)]

def bfs(R, root, dom):
    n = len(R); idx = {v: i for i, v in enumerate(R)}
    par, ref, dep = [0] * n, [0] * n, [0] * n
    seen, frontier = {root}, [root]
    while frontier:
        nxt = []
        for p in frontier:
            for i in range(n):
                if i not in seen and dom(i) and dot(R[p], R[i]) == Q:
                    par[i], ref[i], dep[i] = p, idx[tuple(a - b for a, b in zip(R[p], R[i]))], dep[p] + 1
                    seen.add(i); nxt.append(i)
        frontier = nxt
    assert all(i in seen for i in range(n) if dom(i))
    return par, ref, dep

def lean_list(name, doc, xs):
    body = ",\n  ".join(", ".join(map(str, xs[k:k + 16])) for k in range(0, len(xs), 16))
    return f"/-- {doc} -/\ndef {name} : List ℕ := [\n  {body}]\n"

out = ["""/-
Copyright (c) 2026 Krystal Guo. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Krystal Guo
-/
import LineGraphs.Computations.ListData

/-!
# Reflection trees for C4 on every ordered star

Generated by `LineGraphs/scripts/generate_c4_stars.py`. Indices are positions in the sorted root
tables `E₈viaD₈.rootList`, `E₇.rootList` and `E₆.rootList`. Nothing here is trusted: each tree is
checked by `decide +kernel` in `C4E8Stars.lean`, `C4E7Stars.lean` and `C4E6Stars.lean`. -/

namespace Computations.C4
"""]
for name, R, a0, b0 in MODELS:
    assert dot(R[a0], R[b0]) == -Q
    p1, r1, d1 = bfs(R, a0, lambda i: True)
    p2, r2, d2 = bfs(R, b0, lambda i: dot(R[i], R[a0]) == -Q)
    for i in range(len(R)):
        if dot(R[i], R[a0]) == -Q and i != b0:
            assert dot(R[r2[i]], R[a0]) == 0
    out.append(lean_list(f"{name}RootParents", "Parents in the reflection tree over all roots.", p1))
    out.append(lean_list(f"{name}RootReflections", "Reflecting roots in the tree over all roots.", r1))
    out.append(lean_list(f"{name}RootDepths", "Depths in the tree over all roots.", d1))
    out.append(lean_list(f"{name}StarParents", "Parents in the tree over the roots at product -1 with a₀.", p2))
    out.append(lean_list(f"{name}StarReflections", "Reflecting roots, orthogonal to a₀.", r2))
    out.append(lean_list(f"{name}StarDepths", "Depths in the tree over the roots at product -1 with a₀.", d2))
out.append("end Computations.C4\n")
print("\n".join(out), end="")
