#!/usr/bin/env python3
"""Untrusted data generator. All claims about its output are checked by Lean.
Run from the repository root. Uses only the standard library; no computation here
is part of the proof. Regenerates E8Data.lean and the twelve certificate batches.
"""
from itertools import combinations, product
from pathlib import Path
from lean_output import write_lean

OUT = Path(__file__).resolve().parents[1] / 'Computations'
roots = []
for i, j in combinations(range(8), 2):
    for a, b in product((-2, 2), repeat=2):
        v = [0] * 8
        v[i], v[j] = a, b
        roots.append(v)
for signs in product((-1, 1), repeat=7):
    last = 1
    for s in signs:
        last *= s
    roots.append([*signs, last])

def key(v):
    k = 0
    for x in v:
        k = 5 * k + x + 2
    return k

roots.sort(key=key)

def vector(v):
    return '[' + ', '.join(map(str, v)) + ']'

def tree(vs, indent=2):
    if not vs:
        return '.nil'
    middle = len(vs) // 2
    v = vs[middle]
    pad = '\n' + ' ' * indent
    return f'(.node {key(v)} {vector(v)}{pad}{tree(vs[:middle], indent+2)}{pad}{tree(vs[middle+1:], indent+2)})'

header = '''import LineGraphs.Computations.VectorTree

/-!
# Integer data for E₈

All 240 roots of model (ii) in doubled integer coordinates.
Generated by `generate_e8.py`; this file makes no unverified mathematical assertions. -/

namespace Computations.E₈Data

'''
body = '/-- A balanced membership tree. Each node stores the complete integer vector. -/\n'
body += 'def e₈Tree : VectorTree :=\n  ' + tree(roots) + '\n\n'
body += '/-- The sorted root table read from the balanced tree. -/\n'
body += 'def e₈Roots : List IntVector := e₈Tree.vectors\n\n'
body += '/-- The five possible doubled inner products. -/\n'
body += 'def e₈Allowed : List ℤ := [-8, -4, 0, 4, 8]\n\n'
body += '/-- Twenty roots per certificate, bounding peak kernel memory. -/\n'
body += 'def e₈Chunk (k : ℕ) : List IntVector := (e₈Roots.drop (20 * k)).take 20\n\n'
body += 'end Computations.E₈Data\n'
write_lean(OUT / 'E8Data.lean', header + body, 'Integer data for E₈')
for k in range(12):
    source = f'''import LineGraphs.Computations.E8Data

/-!
# Twenty star rows of E₈

One kernel proof per chunk; shared data are independent of C4.
-/

namespace Computations.C4

open E₈Data

theorem e₈_star_chunk_{k} :
    (e₈Chunk {k}).all (checkStarRow (-4) e₈Tree.contains e₈Roots) = true := by
  decide +kernel

end Computations.C4
'''
    write_lean(OUT / f'E8Rows{k:02d}.lean', source, 'Twenty star rows of E₈')
